-- Ejecútalo una única vez en SQL Editor.
-- Crea tablas, catálogo, RLS y el administrador de prueba.

create extension if not exists pgcrypto;

create type public.user_role as enum ('admin', 'employee');
create type public.employment_type as enum ('employee', 'intern');

create table public.document_types (
  id bigint generated by default as identity primary key,
  name varchar(60) unique not null
);

insert into public.document_types (name)
values
  ('Cédula de ciudadanía'),
  ('Cédula de extranjería'),
  ('Pasaporte')
on conflict do nothing;

create table public.work_schedules (
  id bigint generated by default as identity primary key,
  name varchar(60) unique not null,
  start_time time not null,
  end_time time not null,
  check (end_time > start_time)
);

insert into public.work_schedules (id, name, start_time, end_time)
values
  (1, 'Mañana · 08:00–13:00', '08:00', '13:00'),
  (2, 'Tarde · 13:00–17:00', '13:00', '17:00');

alter sequence public.work_schedules_id_seq restart with 3;

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email varchar(255) unique not null,
  first_name varchar(20) not null check (first_name ~ '^[[:alpha:]]{1,20}$'),
  last_name varchar(20) not null check (last_name ~ '^[[:alpha:]]{1,20}$'),
  document_type varchar(60) not null references public.document_types(name),
  -- El número se cifra con Fernet en Flask antes de llegar a esta columna.
  document_number_encrypted text not null,
  role public.user_role not null default 'employee',
  employment_type public.employment_type not null default 'employee',
  created_at timestamptz not null default now()
);

create table public.attendance (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.profiles(id) on delete cascade,
  attendance_date date not null,
  check_in timestamptz,
  check_out timestamptz,
  -- Turno que se detectó al marcar ingreso; preserva el histórico aunque cambie después.
  work_schedule_id bigint references public.work_schedules(id),
  created_at timestamptz not null default now(),
  unique (employee_id, attendance_date),
  check (check_out is null or check_in is not null)
);
create index attendance_employee_date_idx on public.attendance (employee_id, attendance_date desc);

create table public.verification_codes (
  id bigint generated by default as identity primary key,
  employee_id uuid not null references public.profiles(id) on delete cascade,
  attendance_date date not null,
  code_hash text not null,
  expires_at timestamptz not null,
  attempts smallint not null default 0 check (attempts between 0 and 3),
  used boolean not null default false,
  created_at timestamptz not null default now(),
  unique (employee_id, attendance_date)
);

-- El navegador no consulta estas tablas: Flask usa la clave secreta del servidor.
alter table public.profiles enable row level security;
alter table public.attendance enable row level security;
alter table public.verification_codes enable row level security;
alter table public.document_types enable row level security;
alter table public.work_schedules enable row level security;

-- Recarga la caché de esquema de la API al crear las tablas iniciales.
notify pgrst, 'reload schema';

