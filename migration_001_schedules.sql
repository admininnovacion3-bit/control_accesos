create table if not exists public.work_schedules (
  id bigint generated by default as identity primary key,
  name varchar(60) unique not null,
  start_time time not null,
  end_time time not null,
  check (end_time > start_time)
);

insert into public.work_schedules (id, name, start_time, end_time)
values
  (1, 'Mañana · 08:00–13:00', '08:00', '13:00'),
  (2, 'Tarde · 13:00–17:00', '13:00', '17:00')
on conflict (id) do update
set name = excluded.name, start_time = excluded.start_time, end_time = excluded.end_time;

alter sequence public.work_schedules_id_seq restart with 3;

alter table public.attendance
  add column if not exists work_schedule_id bigint references public.work_schedules(id);

alter table public.work_schedules enable row level security;

